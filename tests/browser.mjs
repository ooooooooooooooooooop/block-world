import {createRequire} from 'node:module';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
process.on('SIGINT',async()=>{await browser.close();process.exit(130);});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
page.setDefaultTimeout(20000);
const watchdog=setTimeout(async()=>{console.error('Browser QA deadline exceeded');await browser.close();},240000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const evidence={startedAt:new Date().toISOString(),checks:[],errors};
await mkdir('artifacts',{recursive:true});
try{
 await page.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded'});
 console.log('QA loading');
 await page.waitForFunction(()=>window.__game,{timeout:120000});
 await page.screenshot({path:'artifacts/welcome.png'});
 console.log('QA ready');
 await page.getByRole('button',{name:'开始我的漫游'}).click();
 await page.waitForTimeout(1600);
 const before=await page.evaluate(()=>window.__game.world.getState());
 await page.keyboard.down('w');await page.waitForTimeout(1500);await page.keyboard.up('w');
 const after=await page.evaluate(()=>window.__game.world.getState());
 evidence.checks.push({name:'keyboard-walk',before,after,passed:after.distanceWalked>before.distanceWalked+.5});
 assert.ok(after.distanceWalked>before.distanceWalked+.5,'键盘行走没有发生有效位移');
 await page.screenshot({path:'artifacts/walking.png'});
 console.log('QA keyboard walk passed');
 await page.getByRole('button',{name:'全市地图'}).click();await page.waitForTimeout(1400);
 assert.equal(await page.locator('#map-panel').isVisible(),true);
 await page.locator('#poi-search').fill('杜甫');assert.ok(await page.locator('.poi-row').count()>0);
 await page.screenshot({path:'artifacts/city-map.png'});
 console.log('QA map passed');
 evidence.checks.push({name:'map-search',passed:true});
 await page.getByRole('button',{name:'关闭地图'}).click();
 await page.keyboard.press('c');await page.getByRole('button',{name:'拍摄照片',exact:true}).click();
 await page.waitForFunction(()=>window.__game.photo?.size>1000,{timeout:30000});
 const photo=await page.evaluate(()=>({type:window.__game.photo.type,size:window.__game.photo.size}));
 assert.equal(photo.type,'image/png');
 await page.getByRole('button',{name:'存入相册',exact:true}).click();await page.waitForTimeout(500);
 assert.equal(await page.locator('#save-photo').textContent(),'已存入相册');
 await page.screenshot({path:'artifacts/photo-preview.png'});
 const downloading=page.waitForEvent('download');await page.locator('#download-photo').click();
 const downloaded=await downloading;await downloaded.saveAs('artifacts/photo.png');
 const png=await readFile('artifacts/photo.png');assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
 assert.equal(png.readUInt32BE(16),1920);assert.equal(png.readUInt32BE(20),1080);
 evidence.checks.push({name:'photo-download',passed:true,width:1920,height:1080,bytes:png.length});
 console.log('QA photo passed');
 evidence.checks.push({name:'photo-png-and-indexeddb',passed:true,...photo});
 await page.getByRole('button',{name:'关闭预览'}).click();await page.getByRole('button',{name:'返回漫游'}).click();
 await page.keyboard.press('p');await page.locator('.album-item').first().waitFor({state:'visible'});assert.equal(await page.locator('.album-item').count(),1);
 await page.getByRole('button',{name:'关闭相册'}).click();
 await page.getByRole('button',{name:'打开设置'}).click();await page.getByRole('button',{name:'保存当前进度',exact:true}).click();
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('block-changsha-progress-v1')));
 assert.ok(stored.distanceWalked>.5);await page.reload();await page.waitForFunction(()=>window.__game,{timeout:120000});
 await page.getByRole('button',{name:'继续上次的旅程'}).click();
 const restored=await page.evaluate(()=>window.__game.world.getState());
 assert.ok(Math.hypot(restored.x-stored.x,restored.z-stored.z)<1);
 evidence.checks.push({name:'progress-reload',passed:true,stored:{x:stored.x,z:stored.z},restored:{x:restored.x,z:restored.z}});
 evidence.final=await page.evaluate(()=>window.__game.world.getState());
 assert.ok(evidence.final.npcCount>0,'真实道路附近未出现路人');
 assert.deepEqual(errors,[]);
 evidence.passed=true;
}catch(e){evidence.passed=false;evidence.failure=e.stack;await page.screenshot({path:'artifacts/failure.png',timeout:10000}).catch(()=>{});throw e;}
finally{clearTimeout(watchdog);evidence.finishedAt=new Date().toISOString();await writeFile('artifacts/browser-check.json',JSON.stringify(evidence,null,2));await browser.close();}
